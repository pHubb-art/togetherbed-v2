/**
 * Writes index.html from data/copy.json, so the story text is real HTML that
 * search engines and screen readers can read. Run after changing the copy:
 *   npm run build
 * When the CMS is connected, this same template is filled from the CMS instead.
 */
import fs from "node:fs";

const root = new URL("../", import.meta.url);
const copy = JSON.parse(fs.readFileSync(new URL("data/copy.json", root), "utf8"));
const escapeHtml = text => String(text).replace(/[&<>"']/g, char => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[char]));

/** Links in the copy point at site sections; this maps them to pages that exist. */
function pageLink(href) {
  return /fit/i.test(href || "") ? "fit/" : null;   // other pages do not exist yet, so their buttons are left out
}

function chapterHtml(chapter, index) {
  const heading = index === 0 ? "h1" : "h2";
  const link = chapter.cta && pageLink(chapter.cta.href);
  const cta = link ? `\n          <a class="btn btn-accent sq" href="${link}">${escapeHtml(chapter.cta.label)}</a>` : "";
  return `
      <section class="chapter wrap" data-chapter="${escapeHtml(chapter.id)}">
        <div class="chapter-card glass sq">
          <p class="eyebrow">${escapeHtml(chapter.eyebrow)}</p>
          <${heading}>${escapeHtml(chapter.headline)}</${heading}>
          <p>${escapeHtml(chapter.body)}</p>${cta}
        </div>
      </section>`;
}

const schema = {
  "@context": "https://schema.org",
  "@type": "Organization",
  name: "TogetherBed",
  description: copy.seo.home.description
};

const html = `<!doctype html>
<!-- Generated by tools/build-home.mjs from data/copy.json. Edit those, not this file. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <title>${escapeHtml(copy.seo.home.title)}</title>
  <meta name="description" content="${escapeHtml(copy.seo.home.description)}">
  <meta name="robots" content="noindex">
  <meta property="og:title" content="${escapeHtml(copy.seo.home.title)}">
  <meta property="og:description" content="${escapeHtml(copy.seo.home.description)}">
  <meta property="og:type" content="website">
  <link rel="icon" href="img/favicon.svg" type="image/svg+xml">
  <link rel="preload" as="image" href="img/bed-poster.webp" fetchpriority="high">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Poppins:wght@300;400;600;700&display=swap">
  <link rel="stylesheet" href="css/tokens.css">
  <link rel="stylesheet" href="css/base.css">
  <link rel="stylesheet" href="css/components.css">
  <link rel="stylesheet" href="css/pages/home.css">
  <script type="application/ld+json">${JSON.stringify(schema)}</script>
  <script type="importmap">{"imports":{"three":"https://cdn.jsdelivr.net/npm/three@0.160.0/build/three.module.min.js","three/addons/":"https://cdn.jsdelivr.net/npm/three@0.160.0/examples/jsm/"}}</script>
</head>
<body>
  <a class="skip-link" href="#story">Skip to the story</a>
  <header class="home-header wrap">
    <a class="logo" href="./" aria-label="TogetherBed home">
      <svg viewBox="0 0 256 66" width="132" height="34" role="img" aria-label="TogetherBed"><use href="img/logo.svg#wordmark"></use></svg>
    </a>
    <a class="btn btn-small btn-quiet sq" href="fit/">${escapeHtml(copy.fit.paths.quick.label)}</a>
  </header>
  <main class="story" id="story">
    <div class="bed-stage" id="bed-stage" aria-hidden="true">
      <img src="img/bed-poster.webp" width="1200" height="900" alt="" decoding="async" fetchpriority="high">
      <canvas id="bed-canvas"></canvas>
    </div>
    <div class="chapters">${copy.home.chapters.map(chapterHtml).join("")}
    </div>
  </main>
  <script type="module" src="js/home/main.js"></script>
</body>
</html>
`;

fs.writeFileSync(new URL("index.html", root), html);
console.log(`index.html written with ${copy.home.chapters.length} chapters`);
